/// каталоги цветов. Правка без смены результата (скорость, рефакторинг) число не трогает. Защищает число тест
/// `generator_fingerprint_test.dart`: он падает, если схема на эталонных картинках изменилась, а число и отпечаток в
/// тесте нет. Журнал версий: `docs/research/generator-versions.md`.
abstract final class GeneratorVersion {
  static const int current = 1;
}
