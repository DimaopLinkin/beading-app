/// Группа комплиментов = триггер. Имена пишутся в `easter_egg_log` и в `ru.json`: переименовывать нельзя.
enum EggGroup {
  /// Проект отмечен как «готово».
  completed,

  /// Каждый 100-й отмеченный ряд.
  rows,

  /// Запуск приложения.
  appStart,

  /// Долгая сессия.
  longSession,

  /// Особая дата из настроек.
  specialDate,

  /// Секрет: 7 нажатий на логотип.
  secret,
}
