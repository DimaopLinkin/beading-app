/// Физический размер одной ячейки схемы в миллиметрах.
///
/// Геометрия сетки зависит только от этого интерфейса ([ADR-0003](../../../docs/decisions/0003-crafts-in-domain.md)):
/// реализации — размер бусины (`BeadSize`) и канва для вышивки (`Fabric`, T36).
///
/// Размеры заданы для «естественного» положения ячейки: отверстие бусины идёт вдоль ряда. Геометрии, где бусина
/// лежит иначе (кирпичный стежок), сами меняют ширину и высоту местами.
abstract interface class CellMetrics {
  /// Ширина ячейки вдоль ряда, мм.
  double get widthMm;

  /// Высота ячейки поперёк ряда, мм.
  double get heightMm;
}
