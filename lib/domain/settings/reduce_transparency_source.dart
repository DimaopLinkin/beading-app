/// Системная настройка «Уменьшить прозрачность» (iOS: Универсальный доступ → Дисплей; macOS: Универсальный доступ →
/// Дисплей). Flutter её не сообщает, значение приходит от платформенного слоя.
abstract interface class ReduceTransparencySource {
  /// Текущее значение. Если платформа не умеет отвечать, `false`.
  Future<bool> current();

  /// Новые значения при смене настройки в системе.
  Stream<bool> get changes;
}
